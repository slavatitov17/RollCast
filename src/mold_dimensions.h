#pragma once	// Защищает описание геометрии от повторного подключения
#include <array>	// Хранит пять отделений монолитного валка
inline constexpr std::size_t sectionCount = 5;	// Задаёт число отделений от прибыли вниз
struct SectionDimensions {	// Хранит размеры цилиндрического отделения
    int diameter;	// Задаёт диаметр в миллиметрах
    int height;	// Задаёт осевую длину в миллиметрах
    bool operator==(const SectionDimensions&) const = default;	// Сравнивает размеры перед сохранением проекта
};	// Завершает описание размеров
using MoldDimensions = std::array<SectionDimensions, sectionCount>;	// Упорядочивает отделения по номерам на схеме
